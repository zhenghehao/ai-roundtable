const dictionaries: Record<LanguageCode, TranslationMap> = {
  en,
  "zh-Hans": zhHans,
  "zh-Hant": zhHant,
  ja,
  es,
  fr,
  de,
  pt,
  ru,
  ar,
  ko,
  it,
  nl
};

export type Translator = (key: TranslationKey, values?: Record<string, string | number>) => string;

export function createTranslator(language: LanguageCode = defaultLanguageCode): Translator {
  const dictionary = dictionaries[language] || dictionaries[defaultLanguageCode];

  return (key, values) => {
    const template = dictionary[key] || zhHans[key] || key;
    if (!values) {
      return template;
    }

    return Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template
    );
  };
}
